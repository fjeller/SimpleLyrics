using System;
using System.Collections.Generic;
using System.Text;

namespace SimpleLyrics.Contracts.Results;

/// ==============================================================================================================================
/// <summary>
/// Specifies the result of a song operation.
/// </summary>
/// ==============================================================================================================================
public enum SongResult
{
	/// ==============================================================================================================================
	/// <summary>
	/// No operation was performed.
	/// </summary>
	/// ==============================================================================================================================
	None = 0,

	/// ==============================================================================================================================
	/// <summary>
	/// The song was successfully added.
	/// </summary>
	/// ==============================================================================================================================
	SongAdded,

	/// ==============================================================================================================================
	/// <summary>
	/// The song was successfully updated.
	/// </summary>
	/// ==============================================================================================================================
	SongUpdated,

	/// ==============================================================================================================================
	/// <summary>
	/// The song was successfully deleted.
	/// </summary>
	/// ==============================================================================================================================
	SongDeleted,

	/// ==============================================================================================================================
	/// <summary>
	/// An error occurred during the operation.
	/// </summary>
	/// ==============================================================================================================================
	Error = 1000,

	/// ==============================================================================================================================
	/// <summary>
	/// The song could not be added to the repository.
	/// </summary>
	/// ==============================================================================================================================
	SongCouldNotBeAdded,

	/// ==============================================================================================================================
	/// <summary>
	/// The song could not be updated in the repository.
	/// </summary>
	/// ==============================================================================================================================
	SongCouldNotBeUpdated,

	/// ==============================================================================================================================
	/// <summary>
	/// The song could not be deleted from the repository.
	/// </summary>
	/// ==============================================================================================================================
	SongCouldNotBeDeleted,

	/// ==============================================================================================================================
	/// <summary>
	/// The song data provided is invalid or incomplete.
	/// </summary>
	/// ==============================================================================================================================
	SongDataIsInvalid
}
